// Read-only check of the med_core parsers against a real GTA III install.
// usage: validate_gta3 <path to GTA III folder>
// Never writes inside the game folder.
#include <algorithm>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <map>
#include <sstream>
#include "../src/core/col.h"
#include "../src/core/dff.h"
#include "../src/core/ide.h"
#include "../src/core/img.h"
#include "../src/core/ipl.h"
#include "../src/core/mapcheck.h"
#include "../src/core/original.h"
#include "../src/core/importer.h"
#include <cstring>
#include <set>
#include "../src/core/textutil.h"
#include "../src/core/txd.h"

using namespace med;
namespace fs = std::filesystem;

static std::string slurp(const fs::path& p, bool& ok) {
    std::ifstream f(p, std::ios::binary);
    ok = static_cast<bool>(f);
    return std::string(std::istreambuf_iterator<char>(f), std::istreambuf_iterator<char>());
}

static std::string fixSlashes(std::string s) {
    for (char& c : s) if (c == '\\') c = '/';
    return s;
}

int main(int argc, char** argv) {
    setvbuf(stdout, nullptr, _IONBF, 0);
    if (argc < 2) {
        std::printf("usage: validate_gta3 <GTA III folder>\n");
        return 2;
    }
    fs::path root = argv[1];
    if (argc >= 4 && std::string(argv[2]) == "--original-table") {
        // Generate src/core/original_gta3.inc from the UNMODIFIED game: per placement of every IPL in gta3.dat its file
        // name, model id and a hash of file, id and position (original.h). Positions are not written out.
        bool ok;
        std::istringstream dat(slurp(root / "data/gta3.dat", ok));
        if (!ok) { std::printf("cannot read data/gta3.dat\n"); return 1; }
        std::ofstream out(argv[3], std::ios::trunc);
        out << "// Generated by `validate_gta3 <GTA III 1.0 folder> --original-table <this file>`. Do not edit by hand.\n";
        out << "// One entry per placement of the original GTA III 1.0 map: IPL file, model id, hash of file + id + position.\n";
        out << "const OriginalEntry kOriginalGta3[] = {\n";
        size_t n = 0;
        std::string line;
        while (std::getline(dat, line)) {
            if (line.rfind("IPL", 0) != 0) continue;
            std::string path = fixSlashes(trim(line.substr(3)));
            bool ok2;
            const std::string text = slurp(root / path, ok2);
            if (!ok2) { std::printf("missing %s\n", path.c_str()); return 1; }
            const IplFile f = parseTextIpl(text, GameVersion::GTA3);
            const std::string key = iplFileKey(path);
            for (const IplInstance& p : f.instances) {
                char b[96];
                std::snprintf(b, sizeof b, "    {\"%s\", %d, 0x%016llxull},\n", key.c_str(), p.id, (unsigned long long)placementHash(key, p.id, p.x, p.y, p.z));
                out << b;
                ++n;
            }
        }
        out << "    {nullptr, 0, 0}};\n";
        std::printf("original table written: %zu placements\n", n);
        return 0;
    }
    if (argc >= 4 && std::string(argv[2]) == "--baseline") {
        // Generate src/core/mapcheck_baseline.inc from the UNMODIFIED game: every LOD without a building, building
        // without a LOD and duplicate placement that the original data has.
        CheckInput ci;
        ci.root = root.string();
        CheckResult cr = checkMap(ci);
        std::ofstream out(argv[3], std::ios::trunc);
        auto emit = [&](const char* name, std::vector<std::string> keys) {
            std::sort(keys.begin(), keys.end());
            out << "const char* const " << name << "[] = {\n";
            for (const std::string& k : keys) out << "    \"" << k << "\",\n";
            out << "    nullptr};\n";
        };
        out << "// Generated by `validate_gta3 <GTA III 1.0 folder> --baseline <this file>`. Do not edit by hand.\n";
        emit("kBaselineLodAlone", cr.lodAloneKeys);
        emit("kBaselineBuildingAlone", cr.buildingAloneKeys);
        emit("kBaselineDuplicates", cr.duplicateKeys);
        std::printf("baseline written: %zu LOD, %zu building, %zu duplicate entries\n", cr.lodAloneKeys.size(), cr.buildingAloneKeys.size(), cr.duplicateKeys.size());
        return 0;
    }
    int problems = 0;

    // ---- IMG ----
    ImgArchive img;
    std::string err;
    if (!ImgArchive::open((root / "models/gta3.img").string(), img, err)) {
        std::printf("IMG: FAILED to open: %s\n", err.c_str());
        return 1;
    }
    uint64_t imgSize = fs::file_size(root / "models/gta3.img");
    int outOfRange = 0, dff = 0, txd = 0, col = 0, other = 0;
    for (const ImgEntry& e : img.entries()) {
        if ((static_cast<uint64_t>(e.offset) + e.size) * kImgSectorSize > imgSize) ++outOfRange;
        std::string n = toLower(e.name);
        if (n.size() > 4 && n.substr(n.size() - 4) == ".dff") ++dff;
        else if (n.size() > 4 && n.substr(n.size() - 4) == ".txd") ++txd;
        else if (n.size() > 4 && n.substr(n.size() - 4) == ".col") ++col;
        else ++other;
    }
    std::printf("IMG: version %d, %zu entries (dff %d, txd %d, col %d, other %d), %d out of range\n", img.version(),
                img.entries().size(), dff, txd, col, other, outOfRange);
    problems += outOfRange;
    // RenderWare clump chunk id is 0x10; texture dictionary is 0x16.
    std::vector<unsigned char> data;
    int badMagic = 0, checked = 0;
    for (const ImgEntry& e : img.entries()) {
        std::string n = toLower(e.name);
        if (n.size() < 4) continue;
        std::string ext = n.substr(n.size() - 4);
        if (ext != ".dff" && ext != ".txd") continue;
        if (e.size == 0) {  // empty placeholders exist in the original game data (plaster, g, stu_man, stu_wom)
            std::printf("  note: %s has zero size in the directory\n", e.name.c_str());
            continue;
        }
        if (!img.extract(e.name, data, err) || data.size() < 4) { ++badMagic; std::printf("  bad entry %s\n", e.name.c_str()); continue; }
        uint32_t id = data[0] | (data[1] << 8) | (data[2] << 16) | (data[3] << 24);
        if (id != (ext == ".dff" ? 0x10u : 0x16u)) ++badMagic;
        ++checked;
    }
    std::printf("IMG: checked %d dff/txd entries, %d with an unexpected RenderWare header\n", checked, badMagic);
    problems += badMagic;

    // ---- DFF ----
    {
        int parsed = 0, failed = 0, badIndex = 0, noGeometry = 0;
        size_t verts = 0, tris = 0, mats = 0, textured = 0, strips = 0;
        std::map<uint32_t, int> versions;
        for (const ImgEntry& e : img.entries()) {
            std::string n = toLower(e.name);
            if (e.size == 0 || n.size() < 4 || n.substr(n.size() - 4) != ".dff") continue;
            img.extract(e.name, data, err);
            DffModel m;
            if (!parseDff(data, m, err)) {
                if (failed++ < 10) std::printf("  DFF %s: %s\n", e.name.c_str(), err.c_str());
                continue;
            }
            ++parsed;
            ++versions[m.version];
            if (m.geometries.empty()) ++noGeometry;
            bool bad = false;
            for (const DffGeometry& g : m.geometries) {
                verts += g.vertexCount();
                tris += g.triangles.size() / 3;
                mats += g.materials.size();
                strips += g.triangleStrips ? 1 : 0;
                for (const DffMaterial& mt : g.materials) textured += mt.textured && !mt.texture.empty();
                for (uint32_t idx : g.triangles) if (idx >= g.vertexCount()) bad = true;
                for (uint16_t mi : g.triangleMaterial) if (mi >= g.materials.size()) bad = true;
                for (const DffSplit& s : g.splits) {
                    if (s.material >= g.materials.size()) bad = true;
                    for (uint32_t idx : s.indices) if (idx >= g.vertexCount()) bad = true;
                }
            }
            for (const DffAtomic& a : m.atomics)
                if (a.frame >= static_cast<int>(m.frames.size()) || a.geometry >= static_cast<int>(m.geometries.size())) bad = true;
            if (bad && badIndex++ < 10) std::printf("  DFF %s: index out of range\n", e.name.c_str());
        }
        std::printf("DFF: parsed %d, failed %d, index errors %d, without geometry %d\n", parsed, failed, badIndex, noGeometry);
        std::printf("DFF: %zu vertices, %zu triangles, %zu materials (%zu textured), %zu strip models\n", verts, tris, mats, textured, strips);
        for (auto& v : versions) std::printf("DFF: version 0x%x x %d\n", v.first, v.second);
        problems += failed + badIndex;
    }

    // ---- TXD ----
    {
        int parsed = 0, failed = 0, empty = 0, ps2 = 0;
        size_t textures = 0, dxt = 0, pal = 0, raw16 = 0, raw32 = 0, opaqueAll = 0;
        std::map<uint32_t, int> platforms;
        for (const ImgEntry& e : img.entries()) {
            std::string n = toLower(e.name);
            if (e.size == 0 || n.size() < 4 || n.substr(n.size() - 4) != ".txd") continue;
            img.extract(e.name, data, err);
            TxdFile t;
            if (!parseTxd(data, t, err)) {
                if (err.find("PS2") != std::string::npos) {  // PS2 leftovers shipped in the PC archive
                    std::printf("  note: TXD %s is in PS2 format (skipped)\n", e.name.c_str());
                    ++ps2;
                    continue;
                }
                if (failed++ < 10) std::printf("  TXD %s: %s\n", e.name.c_str(), err.c_str());
                continue;
            }
            ++parsed;
            if (t.textures.empty()) ++empty;
            for (const TxdTexture& tx : t.textures) {
                ++textures;
                ++platforms[tx.platform];
                if (tx.compressed) ++dxt; else if (tx.paletted) ++pal; else if (tx.depth == 16) ++raw16; else ++raw32;
                bool anyAlpha = false;
                for (size_t i = 3; i < tx.rgba.size(); i += 4) if (tx.rgba[i] != 255) { anyAlpha = true; break; }
                if (!anyAlpha) ++opaqueAll;
            }
        }
        std::printf("TXD: parsed %d, failed %d, PS2-format %d, empty dictionaries %d\n", parsed, failed, ps2, empty);
        std::printf("TXD: %zu textures (dxt %zu, paletted %zu, 16-bit %zu, 32-bit %zu), %zu fully opaque\n", textures, dxt, pal, raw16, raw32, opaqueAll);
        for (auto& p : platforms) std::printf("TXD: platform %u x %d\n", p.first, p.second);
        problems += failed;
    }

    // ---- gta3.dat ----
    bool ok;
    std::string dat = slurp(root / "data/gta3.dat", ok);
    if (!ok) { std::printf("cannot read data/gta3.dat\n"); return 1; }
    std::istringstream in(dat);
    std::string line;
    std::vector<IplInstance> allInsts;
    int saveIdentical = 0, saveDiffers = 0, saveRefused = 0;
    int colFiles = 0, colBad = 0;
    size_t colModels = 0, colSpheres = 0, colBoxes = 0, colFaces = 0, colRewriteSame = 0, colRewriteBad = 0;
    std::set<int> modelIds;  // every id of every IDE section (the importer must not reuse one)
    {  // default.dat's IDE files (default.ide: vehicles, peds, weapons) count too; the rest of this check reads gta3.dat
        bool dok;
        std::istringstream din(slurp(root / "data/default.dat", dok));
        std::string dl;
        while (std::getline(din, dl)) {
            dl = trim(dl);
            if (toLower(dl).rfind("ide ", 0) != 0) continue;
            bool iok;
            const std::string t = slurp(root / fixSlashes(trim(dl.substr(4))), iok);
            if (iok) collectIdeIds(t, modelIds);
        }
    }
    int ideFiles = 0, iplFiles = 0, objs = 0, tobj = 0, insts = 0, warnings = 0, missing = 0, roundTripBad = 0;
    while (std::getline(in, line)) {
        line = trim(line);
        if (isBlankOrComment(line)) continue;
        size_t sp = line.find_first_of(" \t");
        if (sp == std::string::npos) continue;
        std::string kind = toLower(line.substr(0, sp));
        std::string path = fixSlashes(trim(line.substr(sp + 1)));
        if (kind == "colfile") {  // "COLFILE <slot> <path>"
            size_t sp2 = path.find_first_of(" \t");
            if (sp2 == std::string::npos) continue;
            std::string colPath = fixSlashes(trim(path.substr(sp2 + 1)));
            std::string bytes = slurp(root / colPath, ok);
            if (!ok) { std::printf("missing: %s\n", colPath.c_str()); ++missing; continue; }
            std::vector<ColModel> models;
            std::string cerr;
            if (!parseCol(std::vector<unsigned char>(bytes.begin(), bytes.end()), models, cerr)) {
                std::printf("  COL %s: %s\n", colPath.c_str(), cerr.c_str());
                ++colBad;
                continue;
            }
            ++colFiles;
            colModels += models.size();
            // the importer's COL writer must give Rockstar's records back byte for byte
            for (const ColModel& m : models) {
                const std::vector<unsigned char> again = writeColl(m);
                if (again.size() != m.fileSize || std::memcmp(again.data(), bytes.data() + m.fileOffset, m.fileSize) != 0) {
                    if (++colRewriteBad <= 5) std::printf("  COL rewrite differs: %s in %s\n", m.name.c_str(), colPath.c_str());
                } else {
                    ++colRewriteSame;
                }
            }
            for (const ColModel& m : models) { colSpheres += m.spheres.size(); colBoxes += m.boxes.size(); colFaces += m.faces.size(); }
            continue;
        }
        if (kind != "ide" && kind != "ipl") continue;
        std::string text = slurp(root / path, ok);
        if (!ok) { std::printf("missing: %s\n", path.c_str()); ++missing; continue; }
        if (kind == "ide") {
            collectIdeIds(text, modelIds);
            IdeFile f = parseIde(text, GameVersion::GTA3);
            ++ideFiles;
            for (const IdeObject& o : f.objects) (o.timed ? tobj : objs)++;
            warnings += static_cast<int>(f.warnings.size());
            for (const std::string& w : f.warnings) std::printf("  %s: %s\n", path.c_str(), w.c_str());
            IdeFile g = parseIde(writeIde(f), GameVersion::GTA3);
            if (g.objects.size() != f.objects.size() || !g.warnings.empty()) { ++roundTripBad; std::printf("  round trip differs: %s\n", path.c_str()); }
        } else {
            IplFile f = parseTextIpl(text, GameVersion::GTA3);
            ++iplFiles;
            insts += static_cast<int>(f.instances.size());
            allInsts.insert(allInsts.end(), f.instances.begin(), f.instances.end());
            warnings += static_cast<int>(f.warnings.size());
            for (const std::string& w : f.warnings) std::printf("  %s: %s\n", path.c_str(), w.c_str());
            IplFile g = parseTextIpl(writeTextIpl(f), GameVersion::GTA3);
            if (g.instances.size() != f.instances.size() || !g.warnings.empty()) { ++roundTripBad; std::printf("  round trip differs: %s\n", path.c_str()); }
            // MEd-style save of unchanged data: how close is it to the file shipped with the game?
            std::string saved, serr;
            if (!replaceIplInstSection(text, f.instances, GameVersion::GTA3, saved, serr)) {
                // a file with no inst block (for example cull.ipl) has no placements, so it is never saved
                if (f.instances.empty()) {
                    std::printf("  note: %s has no inst block, nothing to save\n", path.c_str());
                } else {
                    std::printf("  save refused for %s: %s\n", path.c_str(), serr.c_str());
                    ++saveRefused;
                }
            } else if (saved == text) {
                ++saveIdentical;
            } else {
                ++saveDiffers;
                size_t d = 0;
                while (d < saved.size() && d < text.size() && saved[d] == text[d]) ++d;
                size_t a = text.rfind('\n', d == 0 ? 0 : d - 1);
                size_t b = text.find('\n', d);
                std::printf("  unchanged re-save differs: %s\n    original: %s\n", path.c_str(),
                            text.substr(a == std::string::npos ? 0 : a + 1, b == std::string::npos ? std::string::npos : b - (a == std::string::npos ? 0 : a + 1)).c_str());
                size_t a2 = saved.rfind('\n', d == 0 ? 0 : d - 1);
                size_t b2 = saved.find('\n', d);
                std::printf("    re-saved: %s\n", saved.substr(a2 == std::string::npos ? 0 : a2 + 1, b2 == std::string::npos ? std::string::npos : b2 - (a2 == std::string::npos ? 0 : a2 + 1)).c_str());
            }
        }
    }
    std::printf("COL: %d files, %zu models (%zu spheres, %zu boxes, %zu faces), %d failed\n", colFiles, colModels, colSpheres, colBoxes, colFaces, colBad);
    problems += colBad;
    std::printf("COL rewrite: %zu records written back byte for byte, %zu differ\n", colRewriteSame, colRewriteBad);
    problems += int(colRewriteBad);
    std::printf("model ids: %zu used (every IDE section), highest %d, first free from %d: %d\n", modelIds.size(), modelIds.empty() ? -1 : *modelIds.rbegin(),
                kGta3FirstFreeId, proposeModelId(modelIds));
    std::printf("IDE: %d files, %d objs, %d tobj\n", ideFiles, objs, tobj);
    std::printf("IPL: %d files, %d inst\n", iplFiles, insts);
    {
        int lods = 0, lodsPaired = 0, hdPaired = 0, orphanPairs = 0;
        for (size_t i = 0; i < allInsts.size(); ++i) {
            const std::string& n = allInsts[i].model;
            bool isLod = n.size() > 3 && toLower(n.substr(0, 3)) == "lod";
            std::vector<size_t> partners = findLodPartners(allInsts, i);
            if (isLod) { ++lods; if (!partners.empty()) ++lodsPaired; }
            else if (!partners.empty()) ++hdPaired;
            // pairing must be symmetric: if A lists B then B lists A
            for (size_t j : partners) {
                std::vector<size_t> back = findLodPartners(allInsts, j);
                if (std::find(back.begin(), back.end(), i) == back.end()) ++orphanPairs;
            }
        }
        std::printf("LOD pairing: %d LOD placements, %d with a building partner within 5 units, %d buildings with a LOD partner, %d asymmetric pairs\n",
                    lods, lodsPaired, hdPaired, orphanPairs);
        problems += orphanPairs;
    }
    {
        CheckInput ci;
        ci.root = root.string();
        CheckResult cr = checkMap(ci);
        std::printf("MAP CHECK: %d error(s), %d warning(s), %d note(s); %d placements, %d models placed\n", cr.count(Severity::Error),
                    cr.count(Severity::Warning), cr.count(Severity::Info), cr.summary.placements, cr.summary.modelsPlaced);
        std::printf("MAP CHECK: LOD without building %d (original %d), building without LOD %d (original %d), duplicates %d (original %d)\n",
                    cr.summary.lodWithoutBuilding, kOriginalLodWithoutBuilding, cr.summary.buildingWithoutLod, kOriginalBuildingWithoutLod,
                    cr.summary.duplicates, kOriginalDuplicates);
        int shown = 0;
        for (const CheckIssue& i : cr.issues) {
            if (i.severity == Severity::Info && i.code != "pool-usage" && i.code != "pool-nearly-full" && i.code != "placement-name-differs") continue;
            if (shown++ < 25) std::printf("  [%s] %s %s:%d  %s\n", i.severity == Severity::Error ? "ERROR" : i.severity == Severity::Warning ? "warning" : "note", i.code.c_str(), i.file.c_str(), i.line, i.message.c_str());
        }
        problems += cr.count(Severity::Error) + cr.count(Severity::Warning);
        // the path budget of the unmodified game: the simulation of the game's path preparation must give these (it
        // was checked against the game's own counts on a modified map, 2026-10-12)
        const PathBudget& pb = cr.summary.paths;
        std::printf("PATHS: %d road objects, %d car + %d ped nodes (%d ped kept), %d car path links, %d connections (tables 1250 / 4930 / 2076 / 10260)\n", pb.objects,
                    pb.carNodes, pb.pedNodesCreated, pb.pedNodesKept, pb.carLinks, pb.connections);
        if (pb.objects != 1213 || pb.nodesPeak() != 4923 || pb.carNodes != 1964 || pb.carLinks != 2071 || pb.connections != 10220) {
            std::printf("PATHS: DIFFERENT from the measured original (1213 objects, 4923 nodes of which 1964 car, 2071 car links, 10220 connections)\n");
            ++problems;
        }
    }
    std::printf("IPL save of unchanged data: %d byte-identical, %d differ, %d refused\n", saveIdentical, saveDiffers, saveRefused);
    problems += saveRefused;
    std::printf("parser warnings: %d, missing files: %d, round-trip differences: %d\n", warnings, missing, roundTripBad);
    problems += warnings + missing + roundTripBad;
    std::printf(problems == 0 ? "RESULT: clean\n" : "RESULT: %d problem(s)\n", problems);
    return problems ? 1 : 0;
}
